const VB_W = 167;
const VB_CENTER = VB_W / 2;
const MORPH_MS = 1000;
const HOLD_MS = 420; // muestra "FLX" un instante antes de morphear

function findHeroLogo(): HTMLImageElement | null {
  return document.querySelector<HTMLImageElement>("header a img, header img");
}

export default function HeroLogoIntro() {
  const svgRef = useRef<SVGSVGElement>(null);
  const wrapRef = useRef<HTMLDivElement>(null);
  const [box, setBox] = useState<{
    left: number;
    top: number;
    width: number;
    height: number;
  } | null>(null);
  const [gone, setGone] = useState(false);
  const logoRef = useRef<HTMLImageElement | null>(null);

  // 1) Localiza el logo del hero, copia su rect y lo oculta durante el intro.
  useEffect(() => {
    if (typeof window === "undefined") return;
    const reduce =
      window.matchMedia?.("(prefers-reduced-motion: reduce)").matches ?? false;
    const desktop = window.matchMedia?.("(min-width: 1024px)").matches ?? false;
    // El logo grande del hero solo existe en desktop (SPEC 39).
    if (reduce || !desktop) {
      setGone(true);
      return;
    }
    let tries = 0;
    let timer: number | undefined;
    const tryStart = () => {
      const img = findHeroLogo();
      const r = img?.getBoundingClientRect();
      // Espera a que el header posicione el logo grande (alto ~64px).
      if (!img || !r || r.height < 30 || r.width < 60) {
        if (tries++ < 40) {
          timer = window.setTimeout(tryStart, 80);
        } else {
          setGone(true);
        }
        return;
      }
      logoRef.current = img;
      img.style.visibility = "hidden";
      setBox({ left: r.left, top: r.top, width: r.width, height: r.height });
    };
    timer = window.setTimeout(tryStart, 250);
    return () => {
      if (timer) clearTimeout(timer);
      if (logoRef.current) logoRef.current.style.visibility = "";
    };
  }, []);

  // 2) Con el overlay ya posicionado, corre el morph FLX → FIBERLUX y al final
  //    revela el logo real.
  useEffect(() => {
    if (!box) return;
    const svg = svgRef.current;
    const wrap = wrapRef.current;
    if (!svg || !wrap) return;

    const paths = Array.from(svg.querySelectorAll<SVGPathElement>("path"));
    if (paths.length !== LETTERS.length) return;

    // Medidas de cada letra (user units) para armar el layout compacto "FLX".
    const bb = paths.map((p) => {
      const b = p.getBBox();
      return { x: b.x, w: b.width, cx: b.x + b.width / 2 };
    });
    const keepIdx = LETTERS.map((l, i) => (l.keep ? i : -1)).filter(
      (i) => i >= 0
    );
    const gap = 3;
    const compactW =
      keepIdx.reduce((s, i) => s + bb[i].w, 0) + gap * (keepIdx.length - 1);
    let cursor = VB_CENTER - compactW / 2;
    // dx = desplazamiento inicial (de su sitio natural a la posición compacta).
    const dx = new Array(LETTERS.length).fill(0);
    keepIdx.forEach((i) => {
      dx[i] = cursor - bb[i].x;
      cursor += bb[i].w + gap;
    });
    // Las letras intermedias arrancan tiradas hacia el centro (y opacas 0).
    LETTERS.forEach((l, i) => {
      if (!l.keep) dx[i] = (VB_CENTER - bb[i].cx) * 0.55;
    });

    let raf = 0;
    let t0 = -1;
    const apply = (e: number) => {
      // Sin blur (nítido); solo el glow del logo que va apareciendo.
      svg.style.filter = `drop-shadow(0 0 10px rgba(214,77,184,${(0.5 * e).toFixed(
        2
      )})) drop-shadow(0 0 26px rgba(150,35,122,${(0.45 * e).toFixed(2)}))`;
      paths.forEach((p, i) => {
        p.style.transform = `translate(${(dx[i] * (1 - e)).toFixed(2)}px, 0px)`;
        if (!LETTERS[i].keep) {
          const oe = Math.max(0, (e - 0.18) / 0.82);
          p.style.opacity = oe.toFixed(3);
        }
      });
    };
    // Estado inicial (FLX, letras intermedias ocultas).
    apply(0);

    const step = (ts: number) => {
      if (t0 < 0) t0 = ts;
      const p = Math.min(1, (ts - t0) / MORPH_MS);
      const e = 1 - Math.pow(1 - p, 3);
      apply(e);
      if (p < 1) raf = requestAnimationFrame(step);
      else finish();
    };
    const finish = () => {
      // Handoff: revela el logo real y desvanece el overlay.
      window.setTimeout(() => {
        if (logoRef.current) logoRef.current.style.visibility = "";
        wrap.style.transition = "opacity 0.35s ease";
        wrap.style.opacity = "0";
        window.setTimeout(() => setGone(true), 380);
      }, 220);
    };
    const hold = window.setTimeout(() => {
      raf = requestAnimationFrame(step);
    }, HOLD_MS);
    return () => {
      cancelAnimationFrame(raf);
      clearTimeout(hold);
    };
  }, [box]);

  if (gone || !box) return null;

  return (
    <div
      ref={wrapRef}
      aria-hidden="true"
      style={{
        position: "fixed",
        left: `${box.left}px`,
        top: `${box.top}px`,
        width: `${box.width}px`,
        height: `${box.height}px`,
        zIndex: 85,
        pointerEvents: "none",
      }}
    >
      <svg
        ref={svgRef}
        viewBox={`0 0 ${VB_W} 24`}
        width="100%"
        height="100%"
        preserveAspectRatio="xMidYMid meet"
        style={{ display: "block", willChange: "filter" }}
      >
        {LETTERS.map((l, i) => (
          <path key={i} d={l.d} fill="#fff" />
        ))}
      </svg>
    </div>
  );
}
